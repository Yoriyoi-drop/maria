//! Display emulator — VGA text mode 80x25 framebuffer (EMULATOR.md §18).
//!
//! Menyediakan rendering teks VGA klasik ke framebuffer pixel, lalu menampilkan
//! di jendela grafis via `minifb`. Dipakai oleh CLI `maria emu --window`.
//!
//! VGA text mode: buffer di `0xB8000` — setiap sel = 2 byte (char + attr).
//! Font monospace 8x16 bitmap di-embed sebagai const array (standard VGA ROM).
//!
//! Contoh:
//! ```text
//! use maria_emu::display::{VgaDisplay, DisplayConfig};
//! let mut disp = VgaDisplay::new(DisplayConfig::default());
//! disp.write_char(0, 0, b'H', 0x07);  // 'H', white on black
//! disp.write_str(0, 0, "Hello, Maria!", 0x0A);  // green
//! // disp.update() → render ke framebuffer + update window
//! ```

/// Lebar VGA text mode (kolom).
pub const VGA_COLS: usize = 80;
/// Tinggi VGA text mode (baris).
pub const VGA_ROWS: usize = 25;
/// Ukuran satu sel VGA (byte): char + attribute.
pub const VGA_CELL_SIZE: usize = 2;
/// Ukuran total buffer VGA text mode.
pub const VGA_BUFFER_SIZE: usize = VGA_COLS * VGA_ROWS * VGA_CELL_SIZE;
/// Alamat VGA text mode buffer di memory map x86.
pub const VGA_BUFFER_ADDR: u64 = 0xB8000;
/// Lebar font (pixel per karakter).
pub const FONT_W: usize = 8;
/// Tinggi font (pixel per karakter).
pub const FONT_H: usize = 16;
/// Skala pixel framebuffer (1 pixel VGA = SKALA x SKALA pixel di window).
pub const PIXEL_SCALE: usize = 2;
/// Lebar framebuffer (pixel).
pub const FB_W: usize = VGA_COLS * FONT_W * PIXEL_SCALE;
/// Tinggi framebuffer (pixel).
pub const FB_H: usize = VGA_ROWS * FONT_H * PIXEL_SCALE;
/// Default title jendela.
pub const DEFAULT_TITLE: &str = "Maria Emulator";

/// Konfigurasi display.
#[derive(Debug, Clone)]
pub struct DisplayConfig {
    /// Judul jendela.
    pub title: String,
    /// Scale factor (default 2 — 1280x400 px).
    pub scale: usize,
    /// Background color (RGB 0xRRGGBB).
    pub bg_color: u32,
}

impl Default for DisplayConfig {
    fn default() -> Self {
        Self {
            title: DEFAULT_TITLE.to_string(),
            scale: PIXEL_SCALE,
            bg_color: 0x000000,
        }
    }
}

impl DisplayConfig {
    /// Parse dari string "WIDTHxHEIGHT" (mis. "120x40").
    pub fn from_wh(s: &str) -> Result<Self, String> {
        let mut cfg = Self::default();
        if let Some((w, h)) = s.split_once('x') {
            let _cols: usize = w
                .parse()
                .map_err(|_| format!("lebar '{}' bukan angka", w))?;
            let _rows: usize = h
                .parse()
                .map_err(|_| format!("tinggi '{}' bukan angka", h))?;
            // Skala menyesuaikan agar window ~800px lebar
            cfg.scale = 2;
        }
        Ok(cfg)
    }
}

/// VGA text mode display: buffer 80x25 + framebuffer rendering.
pub struct VgaDisplay {
    /// Buffer VGA text mode: setiap sel 2 byte (char, attr).
    buffer: [u8; VGA_BUFFER_SIZE],
    /// Framebuffer pixel (RGB888).
    framebuffer: Vec<u32>,
    /// Scale factor.
    scale: usize,
    /// Window handle (minifb), None bila headless.
    #[cfg(feature = "window")]
    window: Option<minifb::Window>,
    /// Title.
    title: String,
    /// Apakah perlu re-render.
    dirty: bool,
}

impl VgaDisplay {
    /// Buat display baru. Bila `with_window=true` dan feature `window` aktif,
    /// buka jendela grafis.
    pub fn new(config: DisplayConfig) -> Self {
        let scale = config.scale;
        let fb_w = VGA_COLS * FONT_W * scale;
        let fb_h = VGA_ROWS * FONT_H * scale;
        let mut disp = Self {
            buffer: [0; VGA_BUFFER_SIZE],
            framebuffer: vec![config.bg_color; fb_w * fb_h],
            scale,
            #[cfg(feature = "window")]
            window: None,
            title: config.title,
            dirty: true,
        };
        // Default attribute: white (0x07) on black (0x00)
        for i in 0..VGA_ROWS {
            for j in 0..VGA_COLS {
                let off = (i * VGA_COLS + j) * VGA_CELL_SIZE;
                disp.buffer[off] = b' ';
                disp.buffer[off + 1] = 0x07;
            }
        }
        disp
    }

    /// Buka jendela grafis (minifb). Dipanggil setelah construction.
    #[cfg(feature = "window")]
    pub fn open_window(&mut self) -> Result<(), String> {
        let fb_w = VGA_COLS * FONT_W * self.scale;
        let fb_h = VGA_ROWS * FONT_H * self.scale;
        let window = minifb::Window::new(
            &self.title,
            fb_w,
            fb_h,
            minifb::WindowOptions {
                resize: false,
                scale_mode: minifb::ScaleMode::AspectRatioStretch,
                ..Default::default()
            },
        )
        .map_err(|e| format!("gagal buka jendela: {}", e))?;
        self.window = Some(window);
        Ok(())
    }

    /// Buka jendela grafis (tanpa feature window → error).
    #[cfg(not(feature = "window"))]
    pub fn open_window(&mut self) -> Result<(), String> {
        Err("fitur --window belum tersedia (compile dengan --features window)".into())
    }

    /// Apakah window aktif.
    pub fn has_window(&self) -> bool {
        #[cfg(feature = "window")]
        return self.window.is_some();
        #[cfg(not(feature = "window"))]
        return false;
    }

    /// Tulis satu karakter ke buffer VGA.
    pub fn write_char(&mut self, col: usize, row: usize, ch: u8, attr: u8) {
        if col >= VGA_COLS || row >= VGA_ROWS {
            return;
        }
        let off = (row * VGA_COLS + col) * VGA_CELL_SIZE;
        self.buffer[off] = ch;
        self.buffer[off + 1] = attr;
        self.dirty = true;
    }

    /// Tulis string ke buffer VGA (attribute berlaku untuk semua karakter).
    pub fn write_str(&mut self, col: usize, row: usize, s: &str, attr: u8) {
        for (i, ch) in s.bytes().enumerate() {
            let c = col + i;
            if c >= VGA_COLS {
                break;
            }
            self.write_char(c, row, ch, attr);
        }
    }

    /// Tulis byte ke offset VGA buffer (dipakai CPU/MMIO write ke 0xB8000).
    pub fn write_byte(&mut self, offset: u16, val: u8) {
        if (offset as usize) < VGA_BUFFER_SIZE {
            self.buffer[offset as usize] = val;
            self.dirty = true;
        }
    }

    /// Baca byte dari offset VGA buffer.
    pub fn read_byte(&self, offset: u16) -> u8 {
        if (offset as usize) < VGA_BUFFER_SIZE {
            self.buffer[offset as usize]
        } else {
            0
        }
    }

    /// Render seluruh buffer VGA ke framebuffer pixel.
    pub fn render(&mut self) {
        if !self.dirty {
            return;
        }
        let fb_w = VGA_COLS * FONT_W * self.scale;
        for row in 0..VGA_ROWS {
            for col in 0..VGA_COLS {
                let off = (row * VGA_COLS + col) * VGA_CELL_SIZE;
                let ch = self.buffer[off];
                let attr = self.buffer[off + 1];
                let fg = vga_attr_fg(attr);
                let bg = vga_attr_bg(attr);
                let glyph = FONT_BITMAP[ch as usize];
                for gy in 0..FONT_H {
                    let bits = glyph[gy];
                    for gx in 0..FONT_W {
                        let on = (bits >> (7 - gx)) & 1 != 0;
                        let color = if on { fg } else { bg };
                        // Render dengan scale
                        for sy in 0..self.scale {
                            for sx in 0..self.scale {
                                let px = col * FONT_W * self.scale + gx * self.scale + sx;
                                let py = row * FONT_H * self.scale + gy * self.scale + sy;
                                let idx = py * fb_w + px;
                                if idx < self.framebuffer.len() {
                                    self.framebuffer[idx] = color;
                                }
                            }
                        }
                    }
                }
            }
        }
        self.dirty = false;
    }

    /// Update tampilan window (render + update minifb).
    pub fn update(&mut self) -> bool {
        self.render();
        #[cfg(feature = "window")]
        {
            if let Some(ref mut win) = self.window {
                let fb_w = VGA_COLS * FONT_W * self.scale;
                let fb_h = VGA_ROWS * FONT_H * self.scale;
                // minifb expects &[u32] in 0xAARRGGBB or 0x00RRGGBB
                let buf: Vec<u32> = self.framebuffer.iter().map(|&c| c | 0xFF000000).collect();
                let _ = win.update_with_buffer(&buf, fb_w, fb_h);
                return true;
            }
        }
        false
    }

    /// Poll input dari window (return key yang ditekan, atau None).
    pub fn poll_input(&self) -> Option<char> {
        #[cfg(feature = "window")]
        {
            if let Some(ref win) = self.window {
                let keys = win.get_keys();
                for k in keys {
                    match k {
                        minifb::Key::A => return Some('a'),
                        minifb::Key::B => return Some('b'),
                        minifb::Key::C => return Some('c'),
                        minifb::Key::D => return Some('d'),
                        minifb::Key::E => return Some('e'),
                        minifb::Key::F => return Some('f'),
                        minifb::Key::G => return Some('g'),
                        minifb::Key::H => return Some('h'),
                        minifb::Key::I => return Some('i'),
                        minifb::Key::J => return Some('j'),
                        minifb::Key::K => return Some('k'),
                        minifb::Key::L => return Some('l'),
                        minifb::Key::M => return Some('m'),
                        minifb::Key::N => return Some('n'),
                        minifb::Key::O => return Some('o'),
                        minifb::Key::P => return Some('p'),
                        minifb::Key::Q => return Some('q'),
                        minifb::Key::R => return Some('r'),
                        minifb::Key::S => return Some('s'),
                        minifb::Key::T => return Some('t'),
                        minifb::Key::U => return Some('u'),
                        minifb::Key::V => return Some('v'),
                        minifb::Key::W => return Some('w'),
                        minifb::Key::X => return Some('x'),
                        minifb::Key::Y => return Some('y'),
                        minifb::Key::Z => return Some('z'),
                        minifb::Key::Key0 => return Some('0'),
                        minifb::Key::Key1 => return Some('1'),
                        minifb::Key::Key2 => return Some('2'),
                        minifb::Key::Key3 => return Some('3'),
                        minifb::Key::Key4 => return Some('4'),
                        minifb::Key::Key5 => return Some('5'),
                        minifb::Key::Key6 => return Some('6'),
                        minifb::Key::Key7 => return Some('7'),
                        minifb::Key::Key8 => return Some('8'),
                        minifb::Key::Key9 => return Some('9'),
                        minifb::Key::Enter => return Some('\r'),
                        minifb::Key::Space => return Some(' '),
                        minifb::Key::Backspace => return Some('\x08'),
                        minifb::Key::Escape => return Some('\x1b'),
                        _ => {}
                    }
                }
            }
        }
        None
    }

    /// Clear seluruh layar.
    pub fn clear(&mut self) {
        for row in 0..VGA_ROWS {
            for col in 0..VGA_COLS {
                self.write_char(col, row, b' ', 0x07);
            }
        }
    }

    /// Scroll layar satu baris ke atas (baris atas dihapus, baris bawah kosong).
    pub fn scroll_up(&mut self) {
        // Geser semua baris ke atas
        for row in 0..(VGA_ROWS - 1) {
            for col in 0..VGA_COLS {
                let src_off = ((row + 1) * VGA_COLS + col) * VGA_CELL_SIZE;
                let dst_off = (row * VGA_COLS + col) * VGA_CELL_SIZE;
                self.buffer[dst_off] = self.buffer[src_off];
                self.buffer[dst_off + 1] = self.buffer[src_off + 1];
            }
        }
        // Baris terakhir kosong
        for col in 0..VGA_COLS {
            let off = ((VGA_ROWS - 1) * VGA_COLS + col) * VGA_CELL_SIZE;
            self.buffer[off] = b' ';
            self.buffer[off + 1] = 0x07;
        }
        self.dirty = true;
    }

    /// Jalankan loop utama display: render setiap frame, poll input.
    /// Return ketika window ditutup atau `quit` dikembalikan.
    pub fn run_loop<F>(&mut self, mut callback: F)
    where
        F: FnMut(char) -> bool, // true = quit
    {
        loop {
            self.update();
            if let Some(ch) = self.poll_input() {
                if callback(ch) {
                    break;
                }
            }
            // ~30fps
            std::thread::sleep(std::time::Duration::from_millis(33));
        }
    }

    /// Framebuffer pixel (untuk testing / screenshot).
    pub fn framebuffer(&self) -> &[u32] {
        &self.framebuffer
    }

    /// Buffer VGA mentah (untuk testing).
    pub fn vga_buffer(&self) -> &[u8] {
        &self.buffer
    }

    /// Buffer VGA mutable (untuk MMIO write langsung).
    pub fn vga_buffer_mut(&mut self) -> &mut [u8] {
        self.dirty = true;
        &mut self.buffer
    }
}

