    #[test]
    fn test_font_bitmap_coverage() {
        // Pastikan semua karakter ASCII printable punya glyph
        // (kecuali space 0x20 yang memang kosong)
        for ch in 0x21..0x7F_u8 {
            let glyph = FONT_BITMAP[ch as usize];
            assert!(
                glyph.iter().any(|&b| b != 0),
                "glyph untuk 0x{:02x} '{}' kosong",
                ch,
                ch as char
            );
        }
        // Space memang kosong (semua 0)
        assert!(FONT_BITMAP[0x20].iter().all(|&b| b == 0), "space harus kosong");
    }
