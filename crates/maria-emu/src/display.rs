/// Konversi VGA attribute byte ke warna foreground RGB (0xRRGGBB).
fn vga_attr_fg(attr: u8) -> u32 {
    let idx = (attr & 0x0F) as usize;
    VGA_PALETTE[idx]
}

/// Konversi VGA attribute byte ke warna background RGB (0xRRGGBB).
fn vga_attr_bg(attr: u8) -> u32 {
    let idx = ((attr >> 4) & 0x0F) as usize;
    VGA_PALETTE[idx]
}

/// Palet warna VGA standar 16 warna (index 0-15 → RGB888).
const VGA_PALETTE: [u32; 16] = [
    0x000000, // 0: Black
    0x0000AA, // 1: Blue
    0x00AA00, // 2: Green
    0x00AAAA, // 3: Cyan
    0xAA0000, // 4: Red
    0xAA00AA, // 5: Magenta
    0xAA5500, // 6: Brown/Dark Yellow
    0xAAAAAA, // 7: Light Gray
    0x555555, // 8: Dark Gray
    0x5555FF, // 9: Light Blue
    0x55FF55, // 10: Light Green
    0x55FFFF, // 11: Light Cyan
    0xFF5555, // 12: Light Red
    0xFF55FF, // 13: Light Magenta
    0xFFFF55, // 14: Yellow
    0xFFFFFF, // 15: White
];

